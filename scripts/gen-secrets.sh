#!/bin/sh
# Генерирует локальные секреты для docker compose.
#
# Запускается командой `make secrets` (и автоматически перед `make dev`).
# Существующие секреты НЕ перезаписываются: база данных инициализируется
# паролем при первом запуске, и новый пароль при старом томе означал бы,
# что control plane больше не сможет к ней подключиться.

set -eu

dir="deploy/compose/secrets"

# umask 077 — всё создаваемое дальше доступно только владельцу. Выставляется
# до создания файлов, а не chmod после: между созданием и chmod файл успел бы
# побыть доступным всем.
umask 077
mkdir -p "$dir"
chmod 700 "$dir"

make_secret() {
    file="$dir/$1"
    if [ -e "$file" ]; then
        echo "секрет $1 уже есть — не перезаписываю"
        return
    fi

    # Криптографически стойкий генератор из стандартной библиотеки Python.
    # Не $RANDOM и не date: предсказуемый пароль — это не пароль.
    python3 -c 'import secrets; print(secrets.token_urlsafe(32), end="")' > "$file"

    # Файл читается внутри контейнера процессом с другим UID (у postgres — 70),
    # поэтому сам файл должен быть доступен на чтение всем. От других
    # пользователей хоста его защищает каталог с правами 700: пройти в него
    # может только владелец.
    chmod 644 "$file"
    echo "секрет $1 создан"
}

make_secret postgres_password

// Package respond содержит единственный способ, которым сенсор отвечает
// сам, без приложения клиента: короткий нейтральный текст.
//
// Одна функция на весь сенсор — чтобы правила таких ответов (без названия
// продукта, без деталей, с запретом угадывать тип) нельзя было соблюсти
// в одном месте и забыть в другом.
package respond

import (
	"io"
	"net/http"
)

// Plain пишет короткий текстовый ответ.
//
// Ответы намеренно не содержат ни названия продукта, ни версии, ни деталей
// ошибки. Ответ сенсора не должен помогать опознать продукт (угроза T5)
// и не должен пересказывать атакующему, что именно пошло не так внутри.
// По той же причине здесь нет заголовка Server: Go его не добавляет,
// и добавлять не нужно.
func Plain(w http.ResponseWriter, status int, body string) {
	w.Header().Set("Content-Type", "text/plain; charset=utf-8")

	// Запрещаем браузеру угадывать тип содержимого вместо объявленного.
	// Для короткого текста это избыточно, но правило должно действовать
	// по умолчанию во всём продукте, а не выборочно.
	w.Header().Set("X-Content-Type-Options", "nosniff")

	w.WriteHeader(status)

	// Ошибку записи намеренно игнорируем: она означает, что клиент отвалился
	// на полуслове. Сделать с этим нечего, а логировать каждый оборванный
	// запрос — значит дать любому желающему бесплатный способ раздуть
	// наш лог до размера диска.
	_, _ = io.WriteString(w, body+"\n")
}

// Package admin содержит служебный HTTP-сервер сенсора: проверки живости
// и готовности.
//
// Служебные эндпоинты живут на отдельном слушателе, а не на том порту,
// через который пойдёт трафик клиента. Причина прямо из модели угроз:
// /healthz на публичном порту — это готовый ответ на вопрос «стоит ли перед
// этим сайтом что-то, кроме самого сайта» (угроза T5), а также точка, куда
// можно слать нагрузку в обход приложения (угроза T3).
package admin

import (
	"io"
	"log/slog"
	"net/http"
	"sync/atomic"
	"time"
)

// Таймауты HTTP-сервера. Вынесены в константы, а не в конфигурацию,
// осознанно: это не настройки под вкус администратора, а защита от класса
// атак, и возможность выставить их в ноль — это возможность отключить защиту.
const (
	// ReadHeaderTimeout — сколько ждём заголовки запроса.
	//
	// Главная защита от Slowloris: атакующий открывает тысячи соединений
	// и отправляет заголовки по одному байту раз в несколько секунд.
	// Каждое такое соединение занимает горутину и память, но формально
	// «работает». Без этого таймаута соединение живёт, пока не кончится
	// терпение атакующего, а оно не кончается.
	ReadHeaderTimeout = 5 * time.Second

	// ReadTimeout — сколько ждём весь запрос целиком, включая тело.
	ReadTimeout = 10 * time.Second

	// WriteTimeout — сколько даём на запись ответа. Защищает от зеркальной
	// атаки: клиент запрашивает данные и читает ответ предельно медленно,
	// удерживая соединение.
	WriteTimeout = 10 * time.Second

	// IdleTimeout — сколько держим keep-alive соединение без запросов.
	IdleTimeout = 60 * time.Second

	// MaxHeaderBytes — предел суммарного размера заголовков.
	//
	// Значение Go по умолчанию — 1 МБ на соединение. Для сервера, который
	// отвечает словом "ok", это неоправданно много: тысяча соединений
	// с максимальными заголовками — это гигабайт памяти.
	MaxHeaderBytes = 16 << 10 // 16 КиБ
)

// allowedPaths — полный список путей служебного слушателя. Всё остальное
// получает 404 ещё до маршрутизатора.
var allowedPaths = map[string]struct{}{
	"/healthz": {},
	"/readyz":  {},
}

// onlyKnownPaths отсекает всё, кроме точного совпадения с известным путём.
//
// Зачем это поверх http.ServeMux. Стандартный маршрутизатор Go «причёсывает»
// путь и отвечает редиректом 301 на очищенный вариант: запрос
// /healthz/../etc/passwd превращается в редирект на /etc/passwd.
// Уязвимости здесь нет — Go экранирует значение, а редирект ведёт на тот же
// хост. Но в ответе оказывается путь, который выбрал атакующий, а служебному
// слушателю редиректы не нужны вообще. Правило проекта простое: данные
// атакующего попадают в ответ только там, где без этого не обойтись.
// Здесь — обойтись можно.
//
// Побочная польза: клиент проверки живости, настроенный на слегка неверный
// путь, получает честный 404, а не 301, который он может молча не выполнить.
func onlyKnownPaths(next http.Handler) http.Handler {
	return http.HandlerFunc(func(w http.ResponseWriter, r *http.Request) {
		if _, ok := allowedPaths[r.URL.Path]; !ok {
			writePlain(w, http.StatusNotFound, "not found")
			return
		}
		next.ServeHTTP(w, r)
	})
}

// NewHandler собирает маршруты служебного сервера.
//
// ready — флаг готовности, общий с функцией запуска. Используется
// atomic.Bool, а не обычный bool, потому что флаг пишет одна горутина,
// а читают горутины обработчиков запросов. Обычная переменная здесь —
// гонка данных: без атомарности Go не гарантирует, что читающая горутина
// вообще когда-нибудь увидит новое значение.
func NewHandler(ready *atomic.Bool) http.Handler {
	mux := http.NewServeMux()

	// Шаблон с методом ("GET /healthz") появился в Go 1.22. Запрос другим
	// методом получит 405 без единой строки нашего кода, а GET-шаблон
	// автоматически обслуживает и HEAD. Чем меньше кода на границе
	// с внешним миром, тем меньше мест, где можно ошибиться.

	// /healthz — проверка живости: процесс запущен и отвечает.
	// Отвечает 200 всегда, пока жив процесс.
	mux.HandleFunc("GET /healthz", func(w http.ResponseWriter, _ *http.Request) {
		writePlain(w, http.StatusOK, "ok")
	})

	// /readyz — проверка готовности: сенсор готов обслуживать запросы.
	// Отличие от /healthz принципиальное. Живость отвечает на вопрос
	// «нужно ли перезапустить процесс», готовность — на вопрос «можно ли
	// слать сюда трафик». Во время остановки сенсор жив, но не готов,
	// и балансировщик должен увести трафик, а не убивать процесс.
	mux.HandleFunc("GET /readyz", func(w http.ResponseWriter, _ *http.Request) {
		if !ready.Load() {
			writePlain(w, http.StatusServiceUnavailable, "not ready")
			return
		}
		writePlain(w, http.StatusOK, "ready")
	})

	return onlyKnownPaths(mux)
}

// NewServer оборачивает обработчик в http.Server с безопасными таймаутами.
func NewServer(h http.Handler, logger *slog.Logger) *http.Server {
	return &http.Server{
		Handler:           h,
		ReadHeaderTimeout: ReadHeaderTimeout,
		ReadTimeout:       ReadTimeout,
		WriteTimeout:      WriteTimeout,
		IdleTimeout:       IdleTimeout,
		MaxHeaderBytes:    MaxHeaderBytes,

		// ErrorLog получает ошибки самого HTTP-сервера: битые запросы,
		// сбои разбора протокола, паники в обработчиках. По умолчанию они
		// уходят в глобальный log и теряются среди структурированных
		// сообщений. Перенаправляем их в наш логгер на уровне warn.
		ErrorLog: slog.NewLogLogger(logger.Handler(), slog.LevelWarn),
	}
}

// writePlain пишет короткий текстовый ответ.
//
// Ответы намеренно не содержат ни названия продукта, ни версии, ни деталей
// состояния. Служебный эндпоинт, случайно оказавшийся доступным снаружи,
// не должен помогать опознать продукт (угроза T5). По той же причине здесь
// нет заголовка Server: Go его не добавляет, и добавлять не нужно.
func writePlain(w http.ResponseWriter, status int, body string) {
	w.Header().Set("Content-Type", "text/plain; charset=utf-8")

	// Запрещаем браузеру угадывать тип содержимого вместо объявленного.
	// Для "ok" это избыточно, но правило должно действовать по умолчанию
	// во всём продукте, а не выборочно там, где кто-то вспомнил.
	w.Header().Set("X-Content-Type-Options", "nosniff")

	w.WriteHeader(status)

	// Ошибку записи намеренно игнорируем: она означает, что клиент отвалился
	// на полуслове. Сделать с этим нечего, а логировать каждый оборванный
	// запрос — значит дать любому желающему бесплатный способ раздуть
	// наш лог до размера диска.
	_, _ = io.WriteString(w, body+"\n")
}

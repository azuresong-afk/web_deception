// Package healthcheck — проверка готовности сенсора изнутри контейнера.
//
// Зачем это нужно. Финальный образ сенсора собран на distroless: в нём нет
// shell, curl, wget и вообще ничего, кроме нашего бинарника. Это сознательное
// решение — атакующий, получивший выполнение кода внутри контейнера, не найдёт
// там инструментов. Но и Docker тоже не найдёт, чем опросить /readyz. Поэтому
// проверку умеет делать сам бинарник: `sensor healthcheck`.
//
// Граница доверия: входных данных от атакующего здесь нет. Адрес берётся
// из той же конфигурации, что и у сервера, а ответ приходит от нашего же
// процесса. Мы всё равно ограничиваем время, размер ответа и запрещаем
// редиректы — эти правила действуют везде, а не только там, где «опасно».
package healthcheck

import (
	"context"
	"errors"
	"fmt"
	"io"
	"net"
	"net/http"
	"time"
)

// Timeout — сколько ждём ответа. Docker по умолчанию прерывает проверку
// через 30 секунд, но зависшая проверка сама по себе — признак проблемы,
// и узнать о ней нужно быстро.
const Timeout = 2 * time.Second

// maxBodyBytes — сколько байт ответа мы готовы прочитать. Наш ответ —
// "ready\n", шесть байт. Предел нужен не из недоверия к себе, а потому,
// что чтение без предела — это привычка, которая однажды окажется там,
// где ответ пришлёт уже не наш сервер.
const maxBodyBytes = 1 << 10

// TargetURL строит адрес проверки по адресу служебного слушателя.
//
// Если слушатель привязан ко всем интерфейсам ("0.0.0.0:9090", ":9090",
// "[::]:9090"), подключаемся к локальному адресу: «все интерфейсы» — это
// адрес для прослушивания, а не для подключения.
func TargetURL(adminAddr string) (string, error) {
	host, port, err := net.SplitHostPort(adminAddr)
	if err != nil {
		return "", fmt.Errorf("адрес служебного слушателя %q: %w", adminAddr, err)
	}

	switch host {
	case "", "0.0.0.0":
		host = "127.0.0.1"
	case "::":
		host = "::1"
	}

	// JoinHostPort сам расставит квадратные скобки вокруг IPv6.
	return "http://" + net.JoinHostPort(host, port) + "/readyz", nil
}

// Probe выполняет одну проверку и возвращает nil, если сенсор готов.
//
// Проверяется именно готовность (/readyz), а не живость (/healthz). В Docker
// статус здоровья используется, чтобы зависимые сервисы ждали, пока этот
// будет готов принимать запросы, — это семантика готовности. Перезапускать
// «нездоровый» контейнер Docker сам не станет: это делает только оркестратор,
// и он будет опрашивать оба эндпоинта напрямую по HTTP, без этой команды.
func Probe(ctx context.Context, url string) error {
	client := &http.Client{
		Timeout: Timeout,
		// Редиректы не выполняем. Проверка здоровья обращается к одному
		// конкретному адресу; ответ «иди в другое место» — это сбой,
		// а не повод пойти туда.
		CheckRedirect: func(*http.Request, []*http.Request) error {
			return http.ErrUseLastResponse
		},
	}

	req, err := http.NewRequestWithContext(ctx, http.MethodGet, url, nil)
	if err != nil {
		return fmt.Errorf("не удалось сформировать запрос: %w", err)
	}

	resp, err := client.Do(req)
	if err != nil {
		return fmt.Errorf("сенсор не ответил: %w", err)
	}
	defer func() { _ = resp.Body.Close() }()

	// Дочитываем тело в пределах лимита, чтобы соединение закрылось чисто.
	_, _ = io.Copy(io.Discard, io.LimitReader(resp.Body, maxBodyBytes))

	if resp.StatusCode != http.StatusOK {
		return errors.New("сенсор не готов: код ответа " + resp.Status)
	}
	return nil
}
